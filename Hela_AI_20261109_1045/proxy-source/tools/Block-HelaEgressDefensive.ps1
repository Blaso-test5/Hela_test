#Requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateNotNullOrEmpty()]
    [string]$GameDirectory,

    [Parameter(Mandatory = $true)]
    [ValidateSet('Apply', 'Verify', 'Remove')]
    [string]$Mode
)

$ErrorActionPreference = 'Stop'
$ruleGroup = 'HelaEgressBlockDefensive'
$ruleDescription = 'HelaEgressBlockDefensive/v1'
$diagnosticStage = 'initialization'
$createdRules = @()
$report = [ordered]@{
    schema = 'hela-egress-control/v1'
    mode = $Mode
    status = 'running'
    identity = $null
    administrator = $false
    policyStore = 'ActiveStore'
    profiles = @()
    targets = @()
    runtimeImageChecks = @()
    configVerified = $false
    enforcementProven = $false
    limitations = @(
        'Rule verification confirms Windows Firewall configuration only, not packet enforcement.',
        'No game is launched and no network traffic is generated by this tool.',
        'For a guaranteed zero-egress run, the operator must manually disconnect network-capable interfaces.'
    )
}

function Get-NormalizedPath {
    param([Parameter(Mandatory = $true)][string]$Path)

    return [System.IO.Path]::GetFullPath($Path).TrimEnd([char[]]@('\', '/'))
}

function Test-AnyFilterValue {
    param([Parameter(Mandatory = $true)]$Values)

    $items = @($Values | ForEach-Object { [string]$_ })
    return $items.Count -eq 1 -and $items[0] -eq 'Any'
}

function Get-RulesByDisplayName {
    param(
        [Parameter(Mandatory = $true)][ValidateSet('ActiveStore', 'PersistentStore')][string]$Store,
        [Parameter(Mandatory = $true)][string]$DisplayName
    )

    $rules = @(Get-NetFirewallRule -PolicyStore $Store -ErrorAction Stop)
    return @($rules | Where-Object { [string]$_.DisplayName -eq $DisplayName })
}

function Get-OwnedRules {
    param(
        [Parameter(Mandatory = $true)][ValidateSet('ActiveStore', 'PersistentStore')][string]$Store,
        [Parameter(Mandatory = $true)]$Target
    )

    return @(
        Get-RulesByDisplayName -Store $Store -DisplayName $Target.DisplayName |
            Where-Object {
                [string]$_.Group -eq $script:ruleGroup -and
                [string]$_.Description -eq $script:ruleDescription
            }
    )
}

function Test-ValidBlockRule {
    param(
        [Parameter(Mandatory = $true)]$Rule,
        [Parameter(Mandatory = $true)][string]$Program
    )

    if ([string]$Rule.Enabled -ne 'True' -or
        [string]$Rule.Direction -ne 'Outbound' -or
        [string]$Rule.Action -ne 'Block') {
        return $false
    }

    $profileText = [string]$Rule.Profile
    if ($profileText -ne 'Any') {
        $profileNames = @($profileText -split '[,\s]+')
        foreach ($requiredProfile in @('Domain', 'Private', 'Public')) {
            if ($profileNames -notcontains $requiredProfile) {
                return $false
            }
        }
    }

    $expectedProgram = Get-NormalizedPath $Program
    $applicationFilters = @(
        Get-NetFirewallApplicationFilter -AssociatedNetFirewallRule $Rule -ErrorAction Stop
    )
    $matchingApplication = @(
        $applicationFilters | Where-Object {
            $_.Program -and
            [string]::Equals(
                (Get-NormalizedPath ([string]$_.Program)),
                $expectedProgram,
                [System.StringComparison]::OrdinalIgnoreCase)
        }
    )
    if ($matchingApplication.Count -eq 0) {
        return $false
    }

    $addressFilters = @(
        Get-NetFirewallAddressFilter -AssociatedNetFirewallRule $Rule -ErrorAction Stop
    )
    if ($addressFilters.Count -ne 1 -or
        -not (Test-AnyFilterValue $addressFilters[0].LocalAddress) -or
        -not (Test-AnyFilterValue $addressFilters[0].RemoteAddress)) {
        return $false
    }

    $portFilters = @(
        Get-NetFirewallPortFilter -AssociatedNetFirewallRule $Rule -ErrorAction Stop
    )
    if ($portFilters.Count -ne 1) {
        return $false
    }

    $protocol = [string]$portFilters[0].Protocol
    if (($protocol -ne 'Any' -and $protocol -ne '256') -or
        -not (Test-AnyFilterValue $portFilters[0].LocalPort) -or
        -not (Test-AnyFilterValue $portFilters[0].RemotePort)) {
        return $false
    }

    return $true
}

try {
    $diagnosticStage = 'identity-and-path-validation'
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = [Security.Principal.WindowsPrincipal]::new($identity)
    $isAdministrator = $principal.IsInRole(
        [Security.Principal.WindowsBuiltInRole]::Administrator)
    $report.identity = $identity.Name
    $report.administrator = $isAdministrator
    if (-not $isAdministrator) {
        throw 'Run this tool from an elevated PowerShell session. No firewall rules were changed.'
    }

    $resolvedGameDirectory = (Resolve-Path -LiteralPath $GameDirectory -ErrorAction Stop).Path
    $gameRoot = [System.IO.Path]::GetFullPath($resolvedGameDirectory)
    $targetDefinitions = @(
        [pscustomobject]@{
            Name = 'Hela-Win64-Shipping.exe'
            Path = Join-Path $gameRoot 'Binaries\Win64\Hela-Win64-Shipping.exe'
        },
        [pscustomobject]@{
            Name = 'crashpad_handler.exe'
            Path = Join-Path $gameRoot 'Plugins\Sentry\Binaries\Win64\crashpad_handler.exe'
        }
    )

    $targets = @(
        foreach ($definition in $targetDefinitions) {
            if (-not [System.IO.File]::Exists($definition.Path)) {
                throw "Required executable not found: $($definition.Path)"
            }

            $resolvedPath = (Resolve-Path -LiteralPath $definition.Path -ErrorAction Stop).Path
            $hashProvider = [System.Security.Cryptography.SHA256]::Create()
            try {
                $hashBytes = $hashProvider.ComputeHash(
                    [System.Text.Encoding]::UTF8.GetBytes($resolvedPath.ToLowerInvariant()))
            }
            finally {
                $hashProvider.Dispose()
            }
            $pathTag = ([System.BitConverter]::ToString($hashBytes) -replace '-', '').
                Substring(0, 16).ToLowerInvariant()

            [pscustomobject]@{
                Name = $definition.Name
                Path = $definition.Path
                ResolvedPath = $resolvedPath
                DisplayName = "$ruleGroup::$pathTag::$($definition.Name)"
            }
        }
    )

    $diagnosticStage = 'runtime-image-validation'
    $runtimeProcesses = @(
        Get-CimInstance -ClassName Win32_Process `
            -Filter "Name='Hela-Win64-Shipping.exe' OR Name='crashpad_handler.exe'" `
            -ErrorAction Stop |
            Where-Object { $_.ExecutablePath }
    )
    $runtimeImageChecks = @(
        foreach ($process in $runtimeProcesses) {
            $processPath = [System.IO.Path]::GetFullPath([string]$process.ExecutablePath)
            $target = $targets |
                Where-Object { $_.Name -ieq [string]$process.Name } |
                Select-Object -First 1
            [ordered]@{
                processName = [string]$process.Name
                processId = [int]$process.ProcessId
                imagePath = $processPath
                matchesRequestedPath = $target -and [string]::Equals(
                    (Get-NormalizedPath $processPath),
                    (Get-NormalizedPath $target.ResolvedPath),
                    [System.StringComparison]::OrdinalIgnoreCase)
            }
        }
    )
    $report.runtimeImageChecks = $runtimeImageChecks
    if ($Mode -eq 'Apply' -and $runtimeProcesses.Count -gt 0) {
        throw 'Close Hela and Crashpad before applying rules; existing connections are not retroactively blocked.'
    }
    if (@($runtimeImageChecks | Where-Object { -not $_.matchesRequestedPath }).Count -gt 0) {
        throw 'A running Hela/Crashpad process uses a different image path. No rules were changed.'
    }

    $diagnosticStage = 'profile-validation'
    $profiles = @(Get-NetFirewallProfile -PolicyStore ActiveStore -ErrorAction Stop)
    $report.profiles = @(
        $profiles | ForEach-Object {
            [ordered]@{
                name = [string]$_.Name
                enabled = [bool]$_.Enabled
                allowLocalFirewallRules = [bool]$_.AllowLocalFirewallRules
            }
        }
    )
    foreach ($profileName in @('Domain', 'Private', 'Public')) {
        $profile = $profiles |
            Where-Object { $_.Name -eq $profileName } |
            Select-Object -First 1
        if (-not $profile -or $profile.Enabled -ne $true) {
            throw "Windows Firewall profile '$profileName' is missing or disabled."
        }
        if ($Mode -eq 'Apply' -and $profile.AllowLocalFirewallRules -ne $true) {
            throw "Local firewall rules are disallowed for profile '$profileName'. No rules were changed."
        }
    }

    if ($Mode -eq 'Apply') {
        $diagnosticStage = 'apply'
        try {
            foreach ($target in $targets) {
                $persistentRules = @(
                    Get-RulesByDisplayName -Store PersistentStore `
                        -DisplayName $target.DisplayName
                )
                $activeRules = @(
                    Get-RulesByDisplayName -Store ActiveStore `
                        -DisplayName $target.DisplayName
                )
                $collisions = @(
                    @($persistentRules) + @($activeRules) |
                        Where-Object {
                            [string]$_.Group -ne $ruleGroup -or
                            [string]$_.Description -ne $ruleDescription
                        }
                )
                if ($collisions.Count -gt 0) {
                    throw "Rule name collision for $($target.Name); refusing to modify an unowned rule."
                }

                $ownedPersistent = @(
                    $persistentRules | Where-Object {
                        [string]$_.Group -eq $ruleGroup -and
                        [string]$_.Description -eq $ruleDescription
                    }
                )
                if ($ownedPersistent.Count -eq 0 -and $activeRules.Count -gt 0) {
                    throw "An ActiveStore rule named for $($target.Name) has no owned PersistentStore rule. Refusing to duplicate or remove a policy-managed rule."
                }
                if ($ownedPersistent.Count -gt 0) {
                    $validPersistent = @(
                        $ownedPersistent | Where-Object {
                            Test-ValidBlockRule -Rule $_ -Program $target.ResolvedPath
                        }
                    )
                    $validActive = @(
                        $activeRules | Where-Object {
                            [string]$_.Group -eq $ruleGroup -and
                            [string]$_.Description -eq $ruleDescription -and
                            (Test-ValidBlockRule -Rule $_ -Program $target.ResolvedPath)
                        }
                    )
                    if ($validPersistent.Count -eq 0 -or $validActive.Count -eq 0) {
                        throw "An owned rule for $($target.Name) exists but is invalid or absent from ActiveStore. Remove it explicitly, then re-apply."
                    }
                    continue
                }

                New-NetFirewallRule `
                    -PolicyStore PersistentStore `
                    -DisplayName $target.DisplayName `
                    -Group $ruleGroup `
                    -Description $ruleDescription `
                    -Direction Outbound `
                    -Program $target.ResolvedPath `
                    -Action Block `
                    -Profile Any `
                    -Protocol Any `
                    -LocalAddress Any `
                    -RemoteAddress Any `
                    -LocalPort Any `
                    -RemotePort Any `
                    -Enabled True `
                    -ErrorAction Stop |
                    Out-Null
                $createdRules += [pscustomobject]@{
                    DisplayName = $target.DisplayName
                }

                $verifiedActive = @(
                    Get-OwnedRules -Store ActiveStore -Target $target |
                        Where-Object {
                            Test-ValidBlockRule -Rule $_ -Program $target.ResolvedPath
                        }
                )
                if ($verifiedActive.Count -eq 0) {
                    throw "The new rule for $($target.Name) did not appear valid in ActiveStore."
                }
            }
        }
        catch {
            $applyError = $_.Exception.Message
            $rollbackErrors = @()
            foreach ($createdRule in $createdRules) {
                try {
                    $persistentCreated = @(
                        Get-RulesByDisplayName -Store PersistentStore `
                            -DisplayName $createdRule.DisplayName |
                            Where-Object {
                                [string]$_.Group -eq $ruleGroup -and
                                [string]$_.Description -eq $ruleDescription
                            }
                    )
                    foreach ($rule in $persistentCreated) {
                        Remove-NetFirewallRule -InputObject $rule -ErrorAction Stop
                    }
                }
                catch {
                    $rollbackErrors += $_.Exception.Message
                }
            }
            if ($rollbackErrors.Count -gt 0) {
                throw "$applyError Rollback failed: $($rollbackErrors -join '; ')"
            }
            throw "$applyError Newly created rules were rolled back."
        }
    }
    elseif ($Mode -eq 'Remove') {
        $diagnosticStage = 'remove'
        foreach ($target in $targets) {
            foreach ($rule in (Get-OwnedRules -Store PersistentStore -Target $target)) {
                Remove-NetFirewallRule -InputObject $rule -ErrorAction Stop
            }
        }
    }

    $diagnosticStage = 'final-verification'
    $targetResults = @(
        foreach ($target in $targets) {
            $activeRules = @(Get-OwnedRules -Store ActiveStore -Target $target)
            $persistentRules = @(Get-OwnedRules -Store PersistentStore -Target $target)
            $validActiveRules = @(
                $activeRules | Where-Object {
                    Test-ValidBlockRule -Rule $_ -Program $target.ResolvedPath
                }
            )
            [ordered]@{
                name = $target.Name
                requestedPath = $target.Path
                resolvedPath = $target.ResolvedPath
                displayName = $target.DisplayName
                activeOwnedRuleCount = $activeRules.Count
                persistentOwnedRuleCount = $persistentRules.Count
                activeRuleValid = $validActiveRules.Count -gt 0
            }
        }
    )
    $report.targets = $targetResults
    if ($Mode -eq 'Remove') {
        $desiredStateVerified = @(
            $targetResults | Where-Object {
                $_.activeOwnedRuleCount -gt 0 -or $_.persistentOwnedRuleCount -gt 0
            }
        ).Count -eq 0
    }
    else {
        $desiredStateVerified = @(
            $targetResults | Where-Object { -not $_.activeRuleValid }
        ).Count -eq 0
    }

    $report.configVerified = $desiredStateVerified
    if (-not $desiredStateVerified) {
        throw "The requested $Mode state was not verified in the Windows Firewall stores."
    }
    $report.status = 'verified'
}
catch {
    $report.status = 'failed'
    $report.stage = $diagnosticStage
    $report.error = $_.Exception.Message
}

$json = ConvertTo-Json -InputObject $report -Depth 8
Write-Output $json
if ($report.status -ne 'verified') {
    $failureMessage = "Hela egress tool failed at '$($report.stage)': $($report.error)"
    [Console]::Error.WriteLine($failureMessage)
    throw $failureMessage
}
